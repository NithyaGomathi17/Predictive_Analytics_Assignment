"""## 1. Simple Linear Regression"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score

# Illustrative data: hours studied and exam score
X = np.array([[1], [2], [3], [4], [5], [6]], dtype=float)
y = np.array([35, 40, 50, 55, 65, 70], dtype=float)

model = LinearRegression()
model.fit(X, y)
pred = model.predict(X)
new_hours = np.array([[7.0]])

print("SIMPLE LINEAR REGRESSION")
print("------------------------")
print(f"Slope: {model.coef_[0]:.2f}")
print(f"Intercept: {model.intercept_:.2f}")
print(f"R-squared: {r2_score(y, pred):.3f}")
print(f"Mean squared error: {mean_squared_error(y, pred):.2f}")
print(f"Predicted score for 7 study hours: {model.predict(new_hours)[0]:.2f}")

plt.scatter(X.ravel(), y, label="Observed data")
plt.plot(X.ravel(), pred, label="Regression line")
plt.xlabel("Hours studied")
plt.ylabel("Exam score")
plt.title("Simple Linear Regression")
plt.legend()
plt.show()

"""## 2. Logistic Regression"""

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

# 0 = Fail, 1 = Pass
X = np.array([[1], [2], [2.5], [3], [4], [5], [6], [7]], dtype=float)
y = np.array([0, 0, 0, 0, 1, 1, 1, 1])

model = LogisticRegression()
model.fit(X, y)
predictions = model.predict(X)
test_hours = np.array([[2], [4.5], [6.5]])

print("LOGISTIC REGRESSION")
print("-------------------")
print(f"Training accuracy: {accuracy_score(y, predictions) * 100:.2f}%")
print("Confusion matrix:")
print(confusion_matrix(y, predictions))
for hours, pred, prob in zip(test_hours.ravel(), model.predict(test_hours),
                             model.predict_proba(test_hours)[:, 1]):
    print(f"Hours={hours:.1f} -> {'Pass' if pred == 1 else 'Fail'} "
          f"(pass probability={prob:.2f})")

"""## 3. SVM and Decision Tree Classification"""

from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline
from sklearn.svm import SVC
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.metrics import accuracy_score, classification_report

iris = load_iris()
X_train, X_test, y_train, y_test = train_test_split(
    iris.data, iris.target, test_size=0.25, random_state=42, stratify=iris.target
)

svm_model = make_pipeline(StandardScaler(), SVC(kernel="linear", random_state=42))
tree_model = DecisionTreeClassifier(max_depth=3, random_state=42)
svm_model.fit(X_train, y_train)
tree_model.fit(X_train, y_train)

svm_pred = svm_model.predict(X_test)
tree_pred = tree_model.predict(X_test)

print("SVM AND DECISION TREE CLASSIFICATION")
print("------------------------------------")
print(f"SVM accuracy: {accuracy_score(y_test, svm_pred) * 100:.2f}%")
print(f"Decision Tree accuracy: {accuracy_score(y_test, tree_pred) * 100:.2f}%")
print("\nFirst 5 test predictions (actual | SVM | Decision Tree):")
for actual, svm, tree in zip(y_test[:5], svm_pred[:5], tree_pred[:5]):
    print(f"{iris.target_names[actual]:12s} | {iris.target_names[svm]:12s} | {iris.target_names[tree]}")

plt.figure(figsize=(14, 7))
plot_tree(tree_model, feature_names=iris.feature_names,
          class_names=iris.target_names, filled=True, rounded=True)
plt.title("Decision Tree trained on Iris dataset")
plt.show()

"""## 4. Naive Bayes Algorithm"""

from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

iris = load_iris()
