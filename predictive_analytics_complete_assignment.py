print(confusion_matrix(y_test, pred))
print("\nClassification report:")
print(classification_report(y_test, pred, target_names=iris.target_names, zero_division=0))

"""## 5. Market Basket Analysis using Association Rules"""

from mlxtend.preprocessing import TransactionEncoder
from mlxtend.frequent_patterns import apriori, association_rules
import pandas as pd

transactions = [
    ["Bread", "Milk"],
    ["Bread", "Diapers", "Beer", "Eggs"],
    ["Milk", "Diapers", "Beer", "Cola"],
    ["Bread", "Milk", "Diapers", "Beer"],
    ["Bread", "Milk", "Diapers", "Cola"],
    ["Bread", "Milk"],
    ["Bread", "Diapers", "Beer"],
    ["Milk", "Diapers", "Beer"],
]

encoder = TransactionEncoder()
encoded = encoder.fit(transactions).transform(transactions)
basket = pd.DataFrame(encoded, columns=encoder.columns_)

frequent_itemsets = apriori(basket, min_support=0.25, use_colnames=True)
rules = association_rules(frequent_itemsets, metric="confidence", min_threshold=0.60)

print("MARKET BASKET ANALYSIS")
print("----------------------")
print("Frequent itemsets (minimum support = 0.25):")
display(frequent_itemsets.assign(itemsets=frequent_itemsets["itemsets"].apply(lambda x: ", ".join(sorted(x))))
        .sort_values(["support", "itemsets"], ascending=[False, True]))

print("\nAssociation rules (confidence >= 0.60):")
if rules.empty:
    print("No rules met the confidence threshold.")
else:
    rules_view = rules[["antecedents", "consequents", "support", "confidence", "lift"]].copy()
    rules_view["antecedents"] = rules_view["antecedents"].apply(lambda x: ", ".join(sorted(x)))
    rules_view["consequents"] = rules_view["consequents"].apply(lambda x: ", ".join(sorted(x)))
    display(rules_view.sort_values(["confidence", "lift"], ascending=False).round(3))

